"""Evaluation report: Markdown rendered only from the computed results (no hand-written numbers)."""

import json
from pathlib import Path
from typing import Any


def _fmt(value: Any) -> str:  # noqa: ANN401 - any metric value
    if value is None:
        return "n/a (undefined: zero denominator)"
    if isinstance(value, float):
        return f"{value:.3f}"
    return str(value)


def _confusion_rows(metrics: dict[str, Any], level: str) -> list[str]:
    m = metrics[level]
    rows = [f"| {k.upper()} | {_fmt(m[k])} |" for k in ("tp", "fp", "tn", "fn")]
    rows += [f"| {k} | {_fmt(m[k])} |" for k in ("precision", "recall", "f1")]
    if "false_positive_rate" in m:
        rows.append(f"| false_positive_rate | {_fmt(m['false_positive_rate'])} |")
    return rows


def render_report(report: dict[str, Any], *, generated_at: str) -> str:
    p, d, e = report["parameters"], report["dataset"], report["evaluation"]
    g = p["generation"]
    sweep = [
        f"| {s['threshold']} | {s['alert_events']} | {_fmt(s['event']['precision'])} | "
        f"{_fmt(s['event']['recall'])} | {_fmt(s['event']['f1'])} |"
        for s in report["calibration_sweep"]
    ]
    lines = [
        "# IoT detection — evaluation report",
        "",
        f"Generated by `python -m iot_lakehouse.evaluation` at {generated_at} (UTC). Every number "
        "below comes from that run; rerunning with the same parameters reproduces them.",
        "",
        "## Parameters",
        "",
        f"- Seed: `{g['seed']}`; period: {g['start']} + {g['days']} days; "
        f"sampling: {g['sampling_interval_seconds']} s",
        f"- Thresholds tried (calibration): {p['thresholds']}; **chosen: {p['chosen_threshold']}**",
        f"- Baseline: {p['baseline_days']} days, at least {p['min_history_days']} days of history",
        f"- Detection window per failure: degradation start - {p['tolerance_before_hours']} h to "
        f"failure + {p['tolerance_after_hours']} h",
        "",
        "## Dataset",
        "",
        f"- Readings checksum: `{d['readings_checksum']}`",
        f"- Equipment: {d['equipment']} ({len(d['calibration_equipment'])} calibration, "
        f"{len(d['evaluation_equipment'])} evaluation); sensors: {d['sensors']}; "
        f"sensor-days: {d['sensor_days']}",
        f"- Failures (ground truth): {d['failures']}; drift episodes: {d['drift_episodes']}",
        "",
        "## Calibration sweep (calibration equipment only, event level)",
        "",
        "| Threshold | Alert events | Precision | Recall | F1 |",
        "|---|---:|---:|---:|---:|",
        *sweep,
        "",
        f"## Evaluation (held-out equipment, threshold {p['chosen_threshold']})",
        "",
        f"Failures: {e['failures']}; alert events: {e['alert_events']}.",
        "",
        "### Event level (one-to-one matching; TN undefined at this level)",
        "",
        "| Metric | Value |",
        "|---|---:|",
        *_confusion_rows(e, "event"),
        "",
        "### Equipment-day level",
        "",
        "| Metric | Value |",
        "|---|---:|",
        *_confusion_rows(e, "day"),
        "",
        "### Detection latency (matched failures)",
        "",
        f"- Median warning before the failure: {_fmt(e['latency']['median_lead_time_hours'])} h",
        f"- Shortest warning: {_fmt(e['latency']['min_lead_time_hours'])} h",
        "",
    ]
    return "\n".join(lines)


def write_report(report: dict[str, Any], directory: Path, *, generated_at: str) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "metrics.json").write_text(
        json.dumps(report, indent=2, sort_keys=True, default=str) + "\n", encoding="utf-8"
    )
    (directory / "REPORT.md").write_text(
        render_report(report, generated_at=generated_at), encoding="utf-8"
    )
